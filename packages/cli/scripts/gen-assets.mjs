// Generates src/generated/assets.ts from the shared files in the Claude Code
// plugin directory (the single source of truth for both engines).
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const plugin = join(here, "..", "..", "..", "plugins", "harness-offload");
const read = (p) => readFileSync(join(plugin, p), "utf8");
const prompts = Object.fromEntries(["read", "summarize", "explore", "write", "ask"].map((t) => [t, read(`prompts/${t}.md`)]));
const out = `// GENERATED by scripts/gen-assets.mjs — do not edit.
export const DEFAULTS_JSON = ${JSON.stringify(JSON.parse(read("config/defaults.json")))} as const;
export const OUTLINE_JSON = ${JSON.stringify(JSON.parse(read("config/outline.json")))} as const;
export const CONNECTORS_JSON = ${JSON.stringify(JSON.parse(read("config/connectors.json")))} as const;
export const PROMPT_TEXT = ${JSON.stringify(prompts, null, 2)} as const;
export const PLUGIN_VERSION = ${JSON.stringify(JSON.parse(read(".claude-plugin/plugin.json")).version)};
export const TASK_CONTRACT = ${JSON.stringify(read("prompts/task-contract.md"))};
`;
mkdirSync(join(here, "..", "src", "generated"), { recursive: true });
writeFileSync(join(here, "..", "src", "generated", "assets.ts"), out);
// The report page (with its embedded fonts) is its own module so that only
// `offload dashboard` loads it — hooks start on every tool call.
writeFileSync(
  join(here, "..", "src", "generated", "dashboard.ts"),
  `// GENERATED by scripts/gen-assets.mjs — do not edit.\nexport const DASHBOARD_HTML = ${JSON.stringify(readFileSync(join(here, "..", "src", "ui", "dashboard.html"), "utf8"))};\n`,
);
console.log("generated src/generated/assets.ts");
